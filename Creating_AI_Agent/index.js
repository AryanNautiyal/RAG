// Cannot use above code as older models are not continued anymore


async function runAgent()
{
    while(true)
    {
        const result = await ai.models.generateContent({
            model: 'gemini-3.5-flash-lite',
            contents : History,
            config: {
                tools,
            },
        });

        if(result.functionCalls && result.functionCalls.length > 0)
        {

            History.push(result.candidates[0].content);

            const functionResponseParts = [];

            for(const functionCall of result.functionCalls)
            {

                const { name, args } = functionCall;

                if(!toolFunctions[name])
                {
                    console.error(`Unknown Function Call : ${name}`);

                    continue;
                }
                
                const response = await toolFunctions[name](args);

                const functionResponsePart = {
                    
                    name,

                    response : {
                        result : response
                    },

                    id : functionCall.id,

                }

                functionResponseParts.push({
                    functionResponse: {
                        name,
                        response: {
                            result: response
                        },
                        id: functionCall.id,
                    }
                });

            }

            if(functionResponseParts.length > 0)
            {

                History.push({
                    role : 'user',
                    parts : functionResponseParts
                });
            }
        }
        else
        {
            History.push({role : 'model', parts : [{text : result.text}]});

            console.log(result.text);

            break; 
        }
    }
}


while(true)
{
    const question = readlineSync.question('Ask me anything : ');

    if(question == 'exit')
    {
        break;
    }

    History.push({
        role : 'user',
        parts : [{text : question}]
    });

    await runAgent();
}

